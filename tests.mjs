import assert from 'node:assert/strict';
import {parseBuderusCSV,mergeRecords,getYear,getComparison,parseNumber,captureDateFromName,getMonth} from './engine.mjs';
const now=new Date('2026-10-08T12:00:00Z');
const csv=(lines)=>`;;VerbrauchteEnergie;VerbrauchteEnergie;VerbrauchteEnergie;Sensoren;Sensoren;Sensoren;\n;;Gesamt;Heizung;Warmwasser;;;;\nKategorie;Zeitstempel;Wärmeerzeuger(kWh);Wärmeerzeuger(kWh);Wärmeerzeuger(kWh);Außentemperatur(C);Raumtemperatur(C);Warmwassertemperatur(C);\n${lines.join('\n')}\n`;
assert.equal(parseNumber('6.208,2'),6208.2);
assert.equal(parseNumber('5.206'),5206);
assert.equal(parseNumber('1,7'),1.7);
assert.equal(parseNumber('-'),null);
assert.equal(captureDateFromName('EnergyData_123_2026_10_08_17_35.csv'),'2026-10-08');
const first=csv(['Monat;2025-10;2.619,3;1.376,4;1.196,3;12,4;-;57,7;', 'Monat;2025-01;-;-;-;-;-;-;', 'Monat;2026-01;6.208,2;5.206;954;1,7;-;58;', 'Monat;2026-10;145,6;0,8;144,7;15,7;-;45,2;']);
const r1=parseBuderusCSV(first,'EnergyData_123_2026_10_08_17_35.csv',now);
assert.equal(r1.rows.length,3);
assert.equal(r1.skippedEmpty,1);
let merge=mergeRecords([],r1.rows);
assert.equal(merge.added,3);
assert.equal(mergeRecords(merge.rows,r1.rows).rows.length,3);
let y=getYear(merge.rows,2026,now);
assert.equal(y.total,6353.8);
assert.equal(y.months[0].gas,6208.2);
assert.equal(y.months[9].partial,true);
assert.equal(y.months[1].gas,null);
assert.equal(getYear(merge.rows,2025,now).months[0].gas,null);
assert.equal(getComparison(merge.rows,2026,2025,now).common.length,0);
assert.equal(getComparison(merge.rows,2026,2025,now).change,null);
const second=csv(['Monat;2026-10;200,5;15,2;185,3;12,9;-;50;', 'Monat;2026-11;3.000;2.000;900;8,1;-;48;']);
const r2=parseBuderusCSV(second,'EnergyData_123_2026_11_25_17_35.csv',new Date('2026-11-25'));
merge=mergeRecords(merge.rows,r2.rows);
assert.equal(merge.rows.length,4);
assert.equal(getMonth(merge.rows,2026,10,new Date('2026-12-08')).gas,200.5);
assert.equal(getMonth(merge.rows,2026,10,new Date('2026-12-08')).partial,false);
assert.equal(getMonth(merge.rows,2026,11,new Date('2026-12-08')).partial,true);
console.log('Engine tests passed');
